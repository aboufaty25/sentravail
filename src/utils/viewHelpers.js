const AVATAR_COLORS = ['bg-blue-600', 'bg-emerald-600', 'bg-amber-600', 'bg-rose-600', 'bg-violet-600', 'bg-teal-600', 'bg-orange-600'];

function escapeHtml(s) {
  return String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
}

// Avatar image or coloured initials fallback.
function avatar(user, size = 'w-10 h-10', text = 'text-sm') {
  if (!user) return '';
  if (user.avatarUrl) {
    return `<img src="${escapeHtml(user.avatarUrl)}" alt="" loading="lazy" class="${size} rounded-full object-cover bg-gray-200 shrink-0">`;
  }
  const color = AVATAR_COLORS[(user.id || 0) % AVATAR_COLORS.length];
  const initials = escapeHtml(`${user.firstName?.[0] || ''}${user.lastName?.[0] || ''}`.toUpperCase());
  return `<span class="${size} ${text} ${color} rounded-full text-white font-semibold inline-flex items-center justify-center shrink-0" aria-hidden="true">${initials}</span>`;
}

function roleLabel(role) {
  return ROLE_LABELS[role] || role;
}

function timeAgo(date) {
  const diff = Math.max(0, (Date.now() - new Date(date).getTime()) / 1000);
  if (diff < 60) return "À l'instant";
  if (diff < 3600) return `${Math.floor(diff / 60)} min`;
  if (diff < 86400) return `${Math.floor(diff / 3600)} h`;
  if (diff < 7 * 86400) return `${Math.floor(diff / 86400)} j`;
  return new Date(date).toLocaleDateString('fr-FR', { day: 'numeric', month: 'short', year: 'numeric' });
}

function formatCount(n) {
  if (n >= 1e6) return `${(n / 1e6).toFixed(1).replace('.0', '')} M`;
  if (n >= 1e3) return `${(n / 1e3).toFixed(1).replace('.0', '')} k`;
  return String(n || 0);
}

// Escapes user text, then turns URLs into safe links. Output with <%- %>.
function richText(text) {
  const escaped = escapeHtml(text);
  return escaped.replace(/\bhttps?:\/\/[^\s<]+[^\s<.,;:!?)\]'"]/g, (url) => {
    const shown = url.replace(/^https?:\/\//, '');
    return `<a href="${url}" class="text-brand-600 hover:underline break-all" target="_blank" rel="nofollow ugc noopener">${shown.length > 50 ? `${shown.slice(0, 47)}…` : shown}</a>`;
  });
}

// Cloudinary delivery: resize + automatic format/quality (WebP/AVIF on capable phones).
function imageUrl(url, width = 800) {
  if (!url) return '';
  if (url.includes('res.cloudinary.com') && url.includes('/upload/')) {
    return url.replace('/upload/', `/upload/c_limit,w_${width},f_auto,q_auto/`);
  }
  return url;
}

function reactionSummary(types) {
  return (types || []).map((t) => REACTIONS[t]?.emoji || '').join('');
}

// "2026-11-12" or Date -> "12 nov. 2026"
function formatDate(value) {
  if (!value) return '';
  const d = typeof value === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(value) ? new Date(`${value}T12:00:00Z`) : new Date(value);
  return d.toLocaleDateString('fr-FR', { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC' });
}

// Days left before a DATEONLY deadline (negative when expired).
function daysLeft(deadline) {
  if (!deadline) return null;
  const end = new Date(`${deadline}T23:59:59Z`).getTime();
  return Math.ceil((end - Date.now()) / 86_400_000) - 1;
}

// {a: 'x', b: ''} -> "?a=x" (empty values dropped)
function queryString(params) {
  const qs = new URLSearchParams(Object.entries(params).filter(([, v]) => v !== '' && v != null)).toString();
  return qs ? `?${qs}` : '';
}

